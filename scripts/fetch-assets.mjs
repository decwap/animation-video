async function get(url) {
  const r = await fetch(url);
  if (!r.ok) throw new Error(`${r.status} ${url}`);
  return Buffer.from(await r.arrayBuffer());
}

async function save(file, url) {
  if (!FORCE && fs.existsSync(file)) return 'kept';
  fs.writeFileSync(file, await get(url));
  return 'got';
}

async function fonts() {
  fs.mkdirSync(FONT_DIR, { recursive: true });
  const css = ['/* Bundled fonts, SIL Open Font License (OFL-*.txt). Generated by scripts/fetch-assets.mjs. */'];
  for (const [family, id, ofl, faces] of FONTS) {
    for (const [weight, style] of faces) {
      const name = `${id}-${weight}-${style}.woff2`;
      const reelsCopy = path.join(REELS_FONTS, 'InstrumentSerif-Italic.woff2');
      if (id === 'instrument-serif' && style === 'italic' && fs.existsSync(reelsCopy) && !fs.existsSync(path.join(FONT_DIR, name))) {
        fs.copyFileSync(reelsCopy, path.join(FONT_DIR, name));
      } else {
        await save(path.join(FONT_DIR, name), `https://cdn.jsdelivr.net/fontsource/fonts/${id}@latest/latin-${weight}-${style}.woff2`);
      }
      css.push(`@font-face { font-family: '${family}'; src: url('${name}') format('woff2'); font-weight: ${weight}; font-style: ${style}; font-display: block; }`);
    }
    await save(path.join(FONT_DIR, `OFL-${family.replace(/ /g, '')}.txt`), `https://raw.githubusercontent.com/google/fonts/main/ofl/${ofl}/OFL.txt`);
  }
  fs.writeFileSync(path.join(FONT_DIR, 'fonts.css'), css.join('\n') + '\n');
  console.log(`fonts: ${FONTS.length} families → ${FONT_DIR}`);
}

async function icons() {
  fs.mkdirSync(ICON_DIR, { recursive: true });
  const missing = [];
  for (const name of ICONS) {
    try { await save(path.join(ICON_DIR, `${name}.svg`), `https://cdn.jsdelivr.net/npm/${LUCIDE}/icons/${name}.svg`); }
    catch { missing.push(name); }
  }
  await save(path.join(ICON_DIR, 'LICENSE-lucide.txt'), `https://cdn.jsdelivr.net/npm/${LUCIDE}/LICENSE`);
  const count = fs.readdirSync(ICON_DIR).filter((f) => f.endsWith('.svg')).length;
  console.log(`icons: ${count} from ${LUCIDE}${missing.length ? ` (not found: ${missing.join(', ')})` : ''}`);
}

await fonts();
await icons();
